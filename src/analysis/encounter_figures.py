"""Figures for the encounter analysis.

Three plots, each making one point that the numbers alone do not carry:
how many rows a single encounter produces, what one of those encounters
actually looks like minute by minute, and how unevenly the positive class is
distributed once overlapping encounters are chained together.

Usage:
    python -m src.analysis.encounter_figures data/processed/<file>_pairs.csv
"""

from __future__ import annotations

import argparse
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

from src.analysis.encounters import (
    DEFAULT_ENCOUNTER_GAP_SECONDS,
    DEFAULT_LATERAL_SEPARATION_NM,
    DEFAULT_VERTICAL_SEPARATION_FT,
    METRES_PER_FOOT,
    READ_CHUNK_ROWS,
    group_by_components,
    group_by_pair_over_time,
    load_positive_pairs,
    summarise_encounters,
)

PROJECT_ROOT = Path(__file__).resolve().parents[2]
DEFAULT_FIGURE_DIR = PROJECT_ROOT / "experiments" / "figures"

INK = "#0f172a"
MUTED = "#64748b"
GRID = "#e2e8f0"
AXIS = "#cbd5e1"
ACCENT = "#3d74b8"
ALERT = "#b45309"
SURFACE = "#ffffff"


def _style(axes: plt.Axes) -> None:
    axes.grid(True, color=GRID, linewidth=0.7)
    axes.set_axisbelow(True)
    for side in ("top", "right"):
        axes.spines[side].set_visible(False)
    for side in ("left", "bottom"):
        axes.spines[side].set_color(AXIS)
    axes.tick_params(labelsize=9, colors=MUTED)
    axes.set_facecolor(SURFACE)


def plot_encounter_anatomy(
    encounters: pd.DataFrame, positive_count: int, output_path: Path
) -> None:
    """How many rows an encounter generates, and how long encounters run."""
    figure, (left, right) = plt.subplots(1, 2, figsize=(12, 4.6))
    figure.patch.set_facecolor(SURFACE)

    observations = encounters["observations"].clip(upper=40)
    left.hist(observations, bins=np.arange(0.5, 40.5, 1), color=ACCENT,
              edgecolor=SURFACE, linewidth=0.5)
    median = encounters["observations"].median()
    left.axvline(median, color=ALERT, linewidth=2, linestyle="--")
    left.annotate(f"median {int(median)}", (median, left.get_ylim()[1] * 0.88),
                  xytext=(8, 0), textcoords="offset points",
                  fontsize=9.5, color=ALERT, fontweight="bold")
    left.set_xlabel("Positive pair-observations generated by one encounter",
                    fontsize=10, color=INK)
    left.set_ylabel("Number of encounters", fontsize=10, color=INK)
    left.set_title("One encounter, many rows", fontsize=12, color=INK,
                   loc="left", fontweight="bold")
    _style(left)

    minutes = encounters["duration_s"] / 60
    right.hist(minutes.clip(upper=20), bins=np.arange(0, 20.5, 0.5), color=ACCENT,
               edgecolor=SURFACE, linewidth=0.5)
    right.set_xlabel("Encounter duration (minutes)", fontsize=10, color=INK)
    right.set_ylabel("Number of encounters", fontsize=10, color=INK)
    right.set_title("How long encounters persist", fontsize=12, color=INK,
                    loc="left", fontweight="bold")
    right.annotate(f"{int((encounters['duration_s'] > 300).sum())} encounters\n"
                   "exceed 5 minutes", (0.62, 0.72), xycoords="axes fraction",
                   fontsize=9.5, color=MUTED)
    _style(right)

    figure.suptitle(
        f"{positive_count:,} positive pair-observations collapse into "
        f"{len(encounters):,} distinct encounters  ·  "
        f"{positive_count / len(encounters):.1f}x inflation",
        fontsize=13, color=INK, x=0.008, ha="left", y=1.005, fontweight="bold")
    figure.tight_layout()
    figure.savefig(output_path, dpi=160, facecolor=SURFACE, bbox_inches="tight")
    plt.close(figure)


def _trace_pair(pairs_path: Path, aircraft_a: str, aircraft_b: str) -> pd.DataFrame:
    """Every observation of one aircraft pair, breaching or not."""
    found = []
    for chunk in pd.read_csv(
        pairs_path,
        usecols=["snapshot_time", "icao24_a", "icao24_b", "lateral_distance_nm",
                 "vertical_separation_m"],
        chunksize=READ_CHUNK_ROWS,
    ):
        low = np.minimum(chunk["icao24_a"], chunk["icao24_b"])
        high = np.maximum(chunk["icao24_a"], chunk["icao24_b"])
        found.append(chunk.loc[(low == aircraft_a) & (high == aircraft_b)])
    return pd.concat(found).sort_values("snapshot_time")


def plot_single_encounter(
    pairs_path: Path, encounters: pd.DataFrame, output_path: Path
) -> tuple[str, str, int]:
    """Trace the longest encounter against both separation limits."""
    longest = encounters.sort_values("observations", ascending=False).iloc[0]
    track = _trace_pair(pairs_path, longest["aircraft_a"], longest["aircraft_b"])

    minutes = (track["snapshot_time"] - track["snapshot_time"].min()) / 60
    vertical_ft = track["vertical_separation_m"] / METRES_PER_FOOT
    breaching = (track["lateral_distance_nm"] <= DEFAULT_LATERAL_SEPARATION_NM) & (
        vertical_ft <= DEFAULT_VERTICAL_SEPARATION_FT
    )

    figure, (upper, lower) = plt.subplots(2, 1, figsize=(11, 6.4), sharex=True)
    figure.patch.set_facecolor(SURFACE)

    panels = [
        (upper, track["lateral_distance_nm"], DEFAULT_LATERAL_SEPARATION_NM,
         "Lateral separation", "nm", "lateral"),
        (lower, vertical_ft, DEFAULT_VERTICAL_SEPARATION_FT,
         "Vertical separation", "ft", "vertical"),
    ]
    for axes, series, limit, label, unit, short in panels:
        axes.plot(minutes, series, color=ACCENT, linewidth=2, zorder=3)
        axes.axhline(limit, color=ALERT, linewidth=1.6, linestyle="--", zorder=2)
        axes.fill_between(minutes, 0, limit, color=ALERT, alpha=0.07, zorder=1)
        axes.annotate(f"{short} limit {limit:g} {unit}", (minutes.max(), limit),
                      xytext=(-4, 6), textcoords="offset points", ha="right",
                      fontsize=9, color=ALERT, fontweight="bold")
        axes.set_ylabel(f"{label} ({unit})", fontsize=10, color=INK)
        # Enough headroom to keep the limit line on the canvas without leaving
        # the trace squashed along the bottom.
        axes.set_ylim(0, max(series.max() * 1.15, limit * 1.25))
        _style(axes)

    upper.scatter(minutes[breaching], track["lateral_distance_nm"][breaching],
                  s=16, color=ALERT, zorder=4, linewidths=0.5, edgecolors=SURFACE)
    upper.set_title(f"A single encounter: {longest['aircraft_a']} and "
                    f"{longest['aircraft_b']}", fontsize=13, color=INK,
                    loc="left", fontweight="bold")
    lower.set_xlabel("Minutes from first observation of this pair",
                     fontsize=10, color=INK)

    figure.tight_layout()
    # The trace fills the lower part of the upper panel, so the caption goes
    # underneath rather than inside the axes.
    figure.subplots_adjust(bottom=0.17)
    figure.text(
        0.008, 0.005,
        f"Both limits are breached in all {int(breaching.sum())} frames of this encounter, "
        f"which lasts {minutes.max():.0f} minutes. That is {int(breaching.sum())} "
        "near-identical positive rows from a single situation;\na random row-level split "
        "scatters them across train and test, so the model is scored on encounters it "
        "already memorised.",
        fontsize=9.5, color=MUTED, ha="left", va="bottom")
    figure.savefig(output_path, dpi=160, facecolor=SURFACE, bbox_inches="tight")
    plt.close(figure)
    return longest["aircraft_a"], longest["aircraft_b"], int(breaching.sum())


def plot_concentration(
    component_id: pd.Series, positive_count: int, output_path: Path
) -> None:
    """Component sizes, and the cumulative share of positives they cover."""
    sizes = component_id.value_counts().sort_values(ascending=False)
    cumulative = sizes.cumsum() / positive_count * 100

    figure, (left, right) = plt.subplots(1, 2, figsize=(12.5, 5.0))
    figure.patch.set_facecolor(SURFACE)

    leading = sizes.head(8)
    labels = [f"#{rank + 1}" for rank in range(len(leading))]
    labels.append(f"other {len(sizes) - len(leading)}")
    values = list(leading.values) + [int(sizes.iloc[len(leading):].sum())]
    positions = np.arange(len(values))[::-1]
    left.barh(positions, values, height=0.72,
              color=[ALERT] + [ACCENT] * (len(values) - 1))
    left.set_yticks(positions, labels, fontsize=9.5)
    left.set_xlabel("Positive pair-observations", fontsize=10, color=INK)
    left.set_title("One component swallows half the positive class",
                   fontsize=12, color=INK, loc="left", fontweight="bold")
    left.annotate(f"{values[0]:,}  ({100 * values[0] / positive_count:.0f}% of all positives)",
                  (values[0], positions[0]), xytext=(-10, 0),
                  textcoords="offset points", ha="right", va="center",
                  fontsize=9.5, color=SURFACE, fontweight="bold")
    _style(left)

    ranks = np.arange(1, len(sizes) + 1)
    right.plot(ranks, cumulative.values, color=ACCENT, linewidth=2.2)
    right.set_xscale("log")
    right.set_xlim(1, len(sizes))
    right.set_ylim(0, 102)
    for rank in (1, 5, 25):
        if rank > len(sizes):
            continue
        share = cumulative.values[rank - 1]
        right.plot([rank], [share], "o", ms=8, color=ALERT,
                   markeredgecolor=SURFACE, markeredgewidth=1.4, zorder=4)
        right.annotate(f"top {rank} = {share:.0f}%", (rank, share),
                       xytext=(9, -13), textcoords="offset points",
                       fontsize=9.5, color=ALERT, fontweight="bold")
    right.set_xlabel("Number of components (largest first, log scale)",
                     fontsize=10, color=INK)
    right.set_ylabel("Cumulative share of positives (%)", fontsize=10, color=INK)
    right.set_title("Grouped splitting has nothing to split", fontsize=12,
                    color=INK, loc="left", fontweight="bold")
    _style(right)

    figure.suptitle(
        f"{positive_count:,} positives form {len(sizes)} connected components "
        "— but they are not remotely equal in size",
        fontsize=13, color=INK, x=0.006, ha="left", y=1.005, fontweight="bold")
    figure.tight_layout()
    figure.subplots_adjust(bottom=0.20)
    figure.text(
        0.006, 0.005,
        "Proximity chains merge aircraft transitively: A near B, B near C, C near D. The "
        "largest component is therefore not one encounter but the\nwhole dense basin, linked "
        "end to end. Any split that keeps components intact puts half the positive class "
        "entirely in train or entirely in\ntest, so a grouped split is unusable here and a "
        "temporal split is the workable alternative.",
        fontsize=9.5, color=MUTED, ha="left", va="bottom")
    figure.savefig(output_path, dpi=160, facecolor=SURFACE, bbox_inches="tight")
    plt.close(figure)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("pairs_path", type=Path, help="Path to a pair-feature CSV.")
    parser.add_argument("--figure-dir", type=Path, default=DEFAULT_FIGURE_DIR)
    parser.add_argument(
        "--encounter-gap-seconds", type=int, default=DEFAULT_ENCOUNTER_GAP_SECONDS
    )
    args = parser.parse_args()

    positives, _ = load_positive_pairs(args.pairs_path)
    if positives.empty:
        print("No positive pair-observations found.")
        return

    encounter_id = group_by_pair_over_time(positives, args.encounter_gap_seconds)
    encounters = summarise_encounters(positives, encounter_id)
    component_id = group_by_components(positives)

    args.figure_dir.mkdir(parents=True, exist_ok=True)
    anatomy = args.figure_dir / "step3_encounter_anatomy.png"
    single = args.figure_dir / "step3_single_encounter.png"
    concentration = args.figure_dir / "step3_positive_concentration.png"

    plot_encounter_anatomy(encounters, len(positives), anatomy)
    aircraft_a, aircraft_b, frames = plot_single_encounter(
        args.pairs_path, encounters, single
    )
    plot_concentration(component_id, len(positives), concentration)

    print(f"Wrote {anatomy.name}")
    print(f"Wrote {single.name}  ({aircraft_a}/{aircraft_b}, {frames} breaching frames)")
    print(f"Wrote {concentration.name}")


if __name__ == "__main__":
    main()
